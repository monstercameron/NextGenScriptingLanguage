#![cfg(feature = "tooling")]
//! NetworkManager dispatcher shims (issue #333). The generated shim is golden-tested,
//! and install and uninstall touch only the file Execute wrote. Every test works in a
//! temporary directory, never in `/etc`.

use flow::service_deployment::{
    apply_hook_install, apply_hook_uninstall, networkmanager_dispatcher_directory,
    plan_hook_install, plan_hook_uninstall, render_network_dispatcher, HookRunSpec, InstallAction,
    UninstallAction, UninstallOutcome, UnitFile, GENERATED_MARKER,
};
use std::fs;
use std::path::Path;
use tempfile::tempdir;

fn dispatcher_spec() -> HookRunSpec {
    HookRunSpec {
        name: "execute-network".into(),
        executable: "/usr/bin/execute".into(),
        program: "/home/cam/vpn.program".into(),
        fingerprint: "sha256:def456".into(),
    }
}

#[test]
fn dispatcher_shim_matches_golden_text() {
    let shim = render_network_dispatcher(&dispatcher_spec()).unwrap();
    assert_eq!(shim.file_name, "execute-network");
    assert_eq!(
        shim.contents,
        "#!/bin/sh\n\
# Generated by Execute. Do not edit by hand.\n\
# Runs one reviewed program on each NetworkManager dispatcher event. The\n\
# interface and action arguments are not passed to the program. exec passes its\n\
# exit status back to NetworkManager.\n\
exec '/usr/bin/execute' run '/home/cam/vpn.program' --confirm sha256:def456\n"
    );
}

#[test]
fn dispatcher_shim_quotes_hostile_paths_and_refuses_bad_input() {
    let mut spec = dispatcher_spec();
    spec.program = "/home/cam/it's $HOME `x`.program".into();
    let shim = render_network_dispatcher(&spec).unwrap();
    assert!(shim
        .contents
        .contains("run '/home/cam/it'\\''s $HOME `x`.program' --confirm sha256:def456\n"));

    let mut newline = dispatcher_spec();
    newline.program = "/home/cam/a\nb".into();
    assert!(render_network_dispatcher(&newline).is_err());

    let mut escape = dispatcher_spec();
    escape.name = "../escape".into();
    assert!(render_network_dispatcher(&escape).is_err());

    let mut dotted = dispatcher_spec();
    dotted.name = "network.sh".into();
    assert!(render_network_dispatcher(&dotted).is_err());

    let mut relative = dispatcher_spec();
    relative.executable = "execute".into();
    assert!(render_network_dispatcher(&relative).is_err());

    let mut spaced = dispatcher_spec();
    spaced.fingerprint = "a b".into();
    assert!(render_network_dispatcher(&spaced).is_err());
}

#[test]
fn dispatcher_directory_sits_under_the_networkmanager_config_root() {
    let root = Path::new("/etc/NetworkManager");
    assert_eq!(
        networkmanager_dispatcher_directory(root),
        Path::new("/etc/NetworkManager/dispatcher.d")
    );
}

#[test]
fn dispatcher_installs_reports_unchanged_and_uninstalls_exactly_its_own_file() {
    let root = tempdir().unwrap();
    let dir = networkmanager_dispatcher_directory(&root.path().join("NetworkManager"));
    let shim = render_network_dispatcher(&dispatcher_spec()).unwrap();

    let plan = plan_hook_install(&dir, &shim).unwrap();
    assert!(!plan.has_refusal());
    assert_eq!(plan.files[0].action, InstallAction::Create);
    assert!(apply_hook_install(&dir, &plan).unwrap().is_installed());
    assert_eq!(
        fs::read_to_string(dir.join("execute-network")).unwrap(),
        shim.contents
    );

    fs::write(dir.join("other-dispatcher"), "#!/bin/sh\necho mine\n").unwrap();
    let again = plan_hook_install(&dir, &shim).unwrap();
    assert_eq!(again.files[0].action, InstallAction::Unchanged);

    let uninstall = plan_hook_uninstall(&dir, "execute-network").unwrap();
    assert!(!uninstall.has_refusal());
    let removed = apply_hook_uninstall(&dir, &uninstall).unwrap();
    assert_eq!(
        removed,
        UninstallOutcome {
            removed: vec!["execute-network".into()],
            absent: vec![],
        }
    );
    assert!(!dir.join("execute-network").exists());
    assert!(dir.join("other-dispatcher").exists());

    let gone = plan_hook_uninstall(&dir, "execute-network").unwrap();
    assert_eq!(gone.entries[0].action, UninstallAction::Absent);
}

#[test]
fn dispatcher_replaces_its_own_shim_when_the_fingerprint_changes() {
    let root = tempdir().unwrap();
    let dir = networkmanager_dispatcher_directory(root.path());
    let first = render_network_dispatcher(&dispatcher_spec()).unwrap();
    let plan = plan_hook_install(&dir, &first).unwrap();
    apply_hook_install(&dir, &plan).unwrap();

    let mut reviewed_again = dispatcher_spec();
    reviewed_again.fingerprint = "sha256:fff000".into();
    let second = render_network_dispatcher(&reviewed_again).unwrap();
    let replan = plan_hook_install(&dir, &second).unwrap();
    assert_eq!(replan.files[0].action, InstallAction::Replace);
    apply_hook_install(&dir, &replan).unwrap();
    assert_eq!(
        fs::read_to_string(dir.join("execute-network")).unwrap(),
        second.contents
    );
}

#[test]
fn dispatcher_refuses_a_foreign_file_and_keeps_it_on_uninstall() {
    let root = tempdir().unwrap();
    let dir = networkmanager_dispatcher_directory(root.path());
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("execute-network"), "#!/bin/sh\necho mine\n").unwrap();

    let shim = render_network_dispatcher(&dispatcher_spec()).unwrap();
    let plan = plan_hook_install(&dir, &shim).unwrap();
    assert!(plan.has_refusal());
    assert!(apply_hook_install(&dir, &plan).is_err());
    assert_eq!(
        fs::read_to_string(dir.join("execute-network")).unwrap(),
        "#!/bin/sh\necho mine\n"
    );

    let uninstall = plan_hook_uninstall(&dir, "execute-network").unwrap();
    assert!(uninstall.has_refusal());
    assert!(apply_hook_uninstall(&dir, &uninstall).is_err());
    assert!(dir.join("execute-network").exists());
}

#[test]
fn dispatcher_rejects_unit_style_contents_without_the_shebang() {
    let root = tempdir().unwrap();
    let dir = networkmanager_dispatcher_directory(root.path());
    let unit_style = UnitFile {
        file_name: "execute-network".into(),
        contents: format!("{GENERATED_MARKER}\n"),
    };
    assert!(plan_hook_install(&dir, &unit_style).is_err());
}

#[cfg(unix)]
#[test]
fn dispatcher_shim_is_written_executable() {
    use std::os::unix::fs::PermissionsExt;

    let root = tempdir().unwrap();
    let dir = networkmanager_dispatcher_directory(root.path());
    let shim = render_network_dispatcher(&dispatcher_spec()).unwrap();
    let plan = plan_hook_install(&dir, &shim).unwrap();
    apply_hook_install(&dir, &plan).unwrap();
    let mode = fs::metadata(dir.join("execute-network"))
        .unwrap()
        .permissions()
        .mode();
    assert_eq!(mode & 0o777, 0o755);
}
