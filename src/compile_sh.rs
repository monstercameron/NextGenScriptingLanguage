//! `execute compile --to sh`: a POSIX sh script for the part of a program that has a
//! faithful sh equivalent. Native commands, pipelines, output redirection, command
//! environment, command conditions, literal repeat and for-each loops, `break`,
//! `continue`, `exit`, and `fail` compile. Every other statement is refused by name
//! and line, so no statement is dropped or approximated silently.
//!
//! A pipeline fails when any stage fails, as in execute, without `set -o pipefail`,
//! which dash (the /bin/sh of Debian and Ubuntu) lacks: each stage runs in a brace
//! group that writes its own exit status to a private temporary directory, and the
//! script reads those statuses back after the pipeline. A non-final stage that ends
//! with 141 (killed by SIGPIPE because a later stage stopped reading) is not a
//! failure, matching execute's SIGPIPE convention.
use crate::ast::{
    Connection, Invocation, LoopKind, Program, RedirectTarget, Step, StepKind, Value,
};
use crate::contracts::{AppletBackend, OutcomeKind};
use crate::manifest::{Manifest, Registry};
use anyhow::{bail, Result};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::ops::RangeInclusive;

/// Compile `program` to a POSIX sh script. `source` is the program's exact bytes; the
/// header records their SHA-256 so the script can be tied back to its source.
pub fn compile(
    program: &Program,
    registry: &Registry,
    source_name: &str,
    source: &[u8],
) -> Result<String> {
    if program.trigger.is_some() {
        bail!("triggered programs cannot compile to sh; run them with execute");
    }
    if !program.inputs.is_empty() {
        bail!(
            "programs with declared inputs cannot compile to sh; supply their values as literals"
        );
    }
    if !program.definitions.is_empty() {
        bail!("reusable program definitions cannot compile to sh; inline their statements");
    }
    let mut emitter = Emitter {
        registry,
        steps: &program.steps,
        lines: Vec::new(),
        loops: Vec::new(),
        next_id: 0,
        pipelines: false,
    };
    emitter.block(0, program.steps.len(), 0)?;
    let digest = Sha256::digest(source);
    let mut script = String::new();
    script.push_str("#!/bin/sh\n");
    // A directive right after the shebang covers the whole script. SC2217 objects to
    // feeding stdin to commands that do not read it; stdin is closed on purpose.
    script.push_str("# shellcheck disable=SC2217\n");
    script
        .push_str("# Commands run with stdin closed (< /dev/null) on purpose, to match execute.\n");
    let _ = writeln!(
        script,
        "# Generated by execute compile --to sh from {}.",
        sanitize_comment(source_name)
    );
    let _ = writeln!(script, "# Source sha256: {digest:x}");
    script.push_str("# Do not edit; regenerate from the source program.\n");
    script.push_str("set -e\n");
    if emitter.pipelines {
        // Pipeline stages record their statuses here; see `Emitter::group`. The EXIT
        // trap removes the directory on every exit, and the signal traps turn a signal
        // into an exit so that the EXIT trap runs.
        let _ = writeln!(
            script,
            "if ! {STATUS_DIR}=$(mktemp -d) || [ ! -d \"${STATUS_DIR}\" ]; then"
        );
        script.push_str("  echo 'execute: cannot create a temporary directory' >&2\n");
        script.push_str("  exit 70\n");
        script.push_str("fi\n");
        let _ = writeln!(script, "trap 'rm -rf \"${STATUS_DIR}\"' EXIT");
        script.push_str("trap 'exit 129' HUP\n");
        script.push_str("trap 'exit 130' INT\n");
        script.push_str("trap 'exit 143' TERM\n");
    }
    script.push_str("__execute_value=''\n");
    for line in &emitter.lines {
        script.push_str(line);
        script.push('\n');
    }
    script.push_str("printf '%s' \"$__execute_value\"\n");
    script.push_str("exit 0\n");
    Ok(script)
}

/// Print the pipeline value, which is what execute writes before it ends a run.
const PRINT_VALUE: &str = "printf '%s' \"$__execute_value\"";

/// The shell variable naming the script's private directory for pipeline statuses.
const STATUS_DIR: &str = "__execute_dir";

/// The status sh reports for a command killed by SIGPIPE (128 + 13).
const SIGPIPE_STATUS: u8 = 141;

fn sanitize_comment(text: &str) -> String {
    text.chars()
        .map(|c| if c.is_control() { '?' } else { c })
        .collect()
}

/// Quote one word for sh with single quotes; an embedded quote closes and reopens.
fn quote(text: &str) -> Result<String> {
    if text.contains('\0') {
        bail!("a value contains a NUL byte, which sh cannot represent");
    }
    Ok(format!("'{}'", text.replace('\'', "'\\''")))
}

fn is_sh_name(name: &str) -> bool {
    let mut chars = name.chars();
    matches!(chars.next(), Some(first) if first == '_' || first.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
}

fn literal_status(value: &Value, line: usize, range: RangeInclusive<i64>) -> Result<i64> {
    match value {
        Value::Integer(code) if range.contains(code) => Ok(*code),
        _ => bail!(
            "line {line}: exit and fail statuses must be literal integers {}-{} to compile to sh",
            range.start(),
            range.end()
        ),
    }
}

struct Emitter<'a> {
    registry: &'a Registry,
    steps: &'a [Step],
    lines: Vec<String>,
    /// Loop bindings in scope, innermost last. A reference is valid only for these.
    loops: Vec<(String, String)>,
    next_id: usize,
    /// Whether any multi-stage pipeline was emitted, which needs the status directory.
    pipelines: bool,
}

/// One command, ready to render as a pipeline stage.
struct Stage {
    environment: Vec<(String, String)>,
    words: Vec<String>,
    redirects: Vec<String>,
    close_stdin: bool,
}

impl Stage {
    fn render(&self) -> String {
        let mut text = String::new();
        for (name, value) in &self.environment {
            let _ = write!(text, "{name}={value} ");
        }
        text.push_str(&self.words.join(" "));
        for redirect in &self.redirects {
            text.push(' ');
            text.push_str(redirect);
        }
        if self.close_stdin {
            text.push_str(" < /dev/null");
        }
        text
    }
}

/// The environment and redirect steps in front of an invoke, and the invoke's index.
struct Prefix {
    environment: Vec<(String, String)>,
    redirects: Vec<String>,
    invoke: usize,
}

/// The words of one invocation, and whether it discards stderr.
struct Argv {
    words: Vec<String>,
    discard_stderr: bool,
}

impl Emitter<'_> {
    fn push(&mut self, depth: usize, line: &str) {
        self.lines.push(format!("{}{line}", "  ".repeat(depth)));
    }

    fn fresh_name(&mut self, prefix: &str) -> String {
        self.next_id += 1;
        format!("__execute_{prefix}_{}", self.next_id)
    }

    /// Emit the statements in `[start, end)` as one block at `depth`. A block that
    /// emits nothing still needs one command in sh, so it emits `:`.
    fn body(&mut self, start: usize, end: usize, depth: usize) -> Result<()> {
        let before = self.lines.len();
        self.block(start, end, depth)?;
        if self.lines.len() == before {
            self.push(depth, ":");
        }
        Ok(())
    }

    fn block(&mut self, start: usize, end: usize, depth: usize) -> Result<()> {
        let steps = self.steps;
        let mut index = start;
        while index < end {
            let step = &steps[index];
            let line = step.line;
            index = match &step.kind {
                StepKind::Redirect { .. }
                | StepKind::Environment { .. }
                | StepKind::Invoke { .. } => self.group(index, end, depth)?,
                StepKind::Exit { status } => {
                    let code = literal_status(status, line, 0..=255)?;
                    self.push(depth, PRINT_VALUE);
                    self.push(depth, &format!("exit {code}"));
                    index + 1
                }
                StepKind::Fail { message, status } => {
                    let text = self.text(message, line)?;
                    let code = match status {
                        Some(status) => literal_status(status, line, 1..=255)?,
                        None => 1,
                    };
                    self.push(depth, PRINT_VALUE);
                    self.push(depth, &format!("printf '%s\\n' {text} >&2"));
                    self.push(depth, &format!("exit {code}"));
                    index + 1
                }
                StepKind::Loop { kind, end: offset } => {
                    self.loop_statement(index, kind, line, depth)?;
                    index + offset
                }
                StepKind::IfCommand { .. } => self.if_statement(index, end, depth)?,
                StepKind::BreakLoop => {
                    self.require_loop(line, "break")?;
                    self.push(depth, "break");
                    index + 1
                }
                StepKind::ContinueLoop => {
                    self.require_loop(line, "continue")?;
                    self.push(depth, "continue");
                    index + 1
                }
                other => bail!(
                    "line {line}: {} cannot compile to sh; run the program with execute instead",
                    statement_label(other)
                ),
            };
        }
        Ok(())
    }

    fn require_loop(&self, line: usize, keyword: &str) -> Result<()> {
        if self.loops.is_empty() {
            bail!("line {line}: `{keyword}` outside a loop cannot compile to sh");
        }
        Ok(())
    }

    /// Environment and redirect steps precede the invoke they apply to. Collects them
    /// and returns the invoke's index.
    fn prefix(&self, start: usize, end: usize) -> Result<Prefix> {
        let mut environment = Vec::new();
        let mut redirects = Vec::new();
        let mut index = start;
        while index < end {
            let step = &self.steps[index];
            match &step.kind {
                StepKind::Environment { set, unset } => {
                    if !unset.is_empty() {
                        bail!(
                            "line {}: unsetting environment variables cannot compile to sh",
                            step.line
                        );
                    }
                    for (name, value) in set {
                        if name.starts_with("LD_") || name.starts_with("DYLD_") {
                            bail!(
                                "line {}: {name} is read by the dynamic loader before the program starts; a program cannot set it",
                                self.steps[index].line
                            );
                        }
                        if !is_sh_name(name) {
                            bail!(
                                "line {}: environment name {name:?} is not a valid sh name",
                                step.line
                            );
                        }
                        let Value::String(text) = value else {
                            bail!(
                                "line {}: environment value for {name:?} must be literal text",
                                step.line
                            );
                        };
                        environment.push((name.clone(), quote(text)?));
                    }
                }
                StepKind::Redirect { target, path } => {
                    redirects.push(self.redirect(*target, path.as_ref(), step.line)?);
                }
                StepKind::Invoke { .. } => {
                    return Ok(Prefix {
                        environment,
                        redirects,
                        invoke: index,
                    })
                }
                other => bail!(
                    "line {}: {} cannot compile to sh; run the program with execute instead",
                    step.line,
                    statement_label(other)
                ),
            }
            index += 1;
        }
        bail!(
            "line {}: a redirect or environment step has no command after it",
            self.steps[start].line
        )
    }

    /// One pipeline statement: its prefix, a starting command, and the pipe stages
    /// that follow. Returns the index after the statement.
    fn group(&mut self, start: usize, end: usize, depth: usize) -> Result<usize> {
        let Prefix {
            environment,
            redirects,
            invoke,
        } = self.prefix(start, end)?;
        let StepKind::Invoke { connection, .. } = &self.steps[invoke].kind else {
            bail!("internal error: expected a command");
        };
        if *connection != Connection::Start {
            bail!(
                "line {}: a `then` or `pipe to` command has no command before it to compile to sh",
                self.steps[invoke].line
            );
        }
        let mut stages = vec![self.stage(invoke, environment, redirects)?];
        let mut next = invoke + 1;
        while next < end {
            let StepKind::Invoke { connection, .. } = &self.steps[next].kind else {
                break;
            };
            if *connection != Connection::Pipe {
                break;
            }
            let mut stage = self.stage(next, Vec::new(), Vec::new())?;
            // A later stage reads the previous stage's output, not a closed stdin.
            stage.close_stdin = false;
            stages.push(stage);
            next += 1;
        }
        let count = stages.len();
        self.pipelines |= count > 1;
        // A pipeline's own status is its last stage's, so each stage of a multi-stage
        // pipeline records its status in a file instead and the pipeline itself always
        // succeeds. An `if` condition is exempt from `set -e`, and `$?` at the start of
        // the else branch is the condition's status.
        let rendered = if count == 1 {
            stages[0].render()
        } else {
            stages
                .iter()
                .enumerate()
                .map(|(index, stage)| {
                    let file = format!("\"${STATUS_DIR}/{}\"", index + 1);
                    format!(
                        "{{ if {}; then echo 0 >{file}; else echo \"$?\" >{file}; fi; }}",
                        stage.render()
                    )
                })
                .collect::<Vec<_>>()
                .join(" | ")
        };
        // The runtime decides by position: a command followed by another fresh command,
        // or by the end of the program, streams its stdout straight to the terminal and
        // leaves an empty pipeline value. Any other command captures its stdout as the
        // pipeline value, and a failed capture leaves the previous value in place.
        let captures_stderr = stages.iter().any(|stage| {
            stage
                .redirects
                .iter()
                .any(|redirect| redirect.starts_with("2>") && redirect != "2>/dev/null")
        });
        let streams = !captures_stderr
            && match self.steps.get(next).map(|step| &step.kind) {
                None => true,
                Some(StepKind::Invoke {
                    connection: Connection::Start,
                    ..
                }) => true,
                Some(_) => false,
            };
        if streams {
            self.push(depth, "__execute_value=''");
            self.push(depth, &rendered);
            if count > 1 {
                self.push(depth, "__execute_status=0");
                self.pipeline_status(depth, count);
                self.fail_on_status(depth);
            }
            return Ok(next);
        }
        // The `x` sentinel keeps trailing newlines, which command substitution would
        // otherwise strip. The sentinel runs only after a successful command, and a
        // failed substitution carries the command's status out, so no `$?` reads a
        // builtin's status.
        self.push(depth, "__execute_status=0");
        self.push(
            depth,
            &format!("__execute_out=$({rendered} && printf x) || __execute_status=$?"),
        );
        if count > 1 {
            self.pipeline_status(depth, count);
        }
        self.fail_on_status(depth);
        self.push(depth, "__execute_value=${__execute_out%x}");
        Ok(next)
    }

    /// Read back the statuses the stages of a `count`-stage pipeline recorded; the
    /// rightmost failing stage sets `__execute_status`. A non-final stage killed by
    /// SIGPIPE stopped because a later stage finished reading, which execute does not
    /// count as a failure, so only a later stage's own failure fails the pipeline.
    fn pipeline_status(&mut self, depth: usize, count: usize) {
        for stage in 1..=count {
            self.push(
                depth,
                &format!("read -r __execute_stage <\"${STATUS_DIR}/{stage}\""),
            );
            let success = if stage < count {
                format!("0|{SIGPIPE_STATUS}")
            } else {
                "0".to_owned()
            };
            self.push(
                depth,
                &format!(
                    "case $__execute_stage in {success}) ;; *) __execute_status=$__execute_stage ;; esac"
                ),
            );
        }
    }

    /// End the script as execute ends a failed run: print the pipeline value it holds,
    /// then exit with the failing status.
    fn fail_on_status(&mut self, depth: usize) {
        self.push(depth, "if [ \"$__execute_status\" -ne 0 ]; then");
        self.push(depth + 1, PRINT_VALUE);
        self.push(depth + 1, "exit \"$__execute_status\"");
        self.push(depth, "fi");
    }

    fn stage(
        &self,
        index: usize,
        environment: Vec<(String, String)>,
        mut redirects: Vec<String>,
    ) -> Result<Stage> {
        let step = &self.steps[index];
        let StepKind::Invoke { call, .. } = &step.kind else {
            bail!("line {}: expected a command", step.line);
        };
        let argv = self.argv(call, step.line)?;
        if redirects.iter().any(|redirect| redirect == "2>&1") {
            bail!(
                "line {}: merged stderr cannot compile to sh while preserving output order",
                step.line
            );
        }
        if argv.discard_stderr {
            if redirects.iter().any(|redirect| redirect.starts_with("2>")) {
                bail!(
                    "line {}: a command cannot both discard and redirect stderr",
                    step.line
                );
            }
            redirects.push("2>/dev/null".to_owned());
        }
        Ok(Stage {
            environment,
            words: argv.words,
            redirects,
            close_stdin: true,
        })
    }

    /// The words of one invocation. Refuses every option that changes what execute
    /// does with the result: bindings, status and result capture, caching, retries.
    fn argv(&self, call: &Invocation, line: usize) -> Result<Argv> {
        if call.binding.is_some()
            || call.status_binding.is_some()
            || call.result_binding.is_some()
            || call.cache
            || call.retry.is_some()
        {
            bail!(
                "line {line}: a command that binds, keeps status or result, caches, or retries cannot compile to sh"
            );
        }
        if call.direct {
            let mut words = vec![quote(&call.operation)?];
            for (name, value) in &call.parameters {
                if name != "arguments" {
                    bail!("line {line}: direct command parameter {name:?} cannot compile to sh");
                }
                let Value::List(items) = value else {
                    bail!("line {line}: direct command arguments must be a list to compile to sh");
                };
                for item in items {
                    words.push(self.text(item, line)?);
                }
            }
            return Ok(Argv {
                words,
                discard_stderr: call.discard_stderr,
            });
        }
        let manifest = self.registry.resolve_call(call)?;
        ensure_native_command(manifest, line)?;
        let mut literal = BTreeMap::new();
        for (name, value) in &call.parameters {
            if matches!(value, Value::Reference(_)) {
                bail!(
                    "line {line}: applet {} receives a binding; only literal parameters compile to sh",
                    manifest.name
                );
            }
            literal.insert(name.clone(), value.clone());
        }
        let arguments = manifest.build_arguments(&literal)?;
        let mut words = vec![quote(manifest.binary_for(call))?];
        for argument in &arguments {
            words.push(quote(argument)?);
        }
        Ok(Argv {
            words,
            discard_stderr: call.discard_stderr,
        })
    }

    /// Render a value as one sh word: a literal is quoted, and a loop binding in scope
    /// is expanded inside double quotes.
    fn text(&self, value: &Value, line: usize) -> Result<String> {
        match value {
            Value::String(text) => quote(text),
            Value::Integer(number) => Ok(number.to_string()),
            Value::Reference(name) => self
                .loops
                .iter()
                .rev()
                .find(|(binding, _)| binding == name)
                .map(|(_, shell_name)| format!("\"${shell_name}\""))
                .ok_or_else(|| anyhow::anyhow!("line {line}: binding {name:?} is not a loop variable in scope, so it cannot compile to sh")),
            _ => bail!("line {line}: this value kind cannot compile to sh"),
        }
    }

    fn redirect(
        &self,
        target: RedirectTarget,
        path: Option<&Value>,
        line: usize,
    ) -> Result<String> {
        let path = match (target, path) {
            (RedirectTarget::StderrFile | RedirectTarget::StderrAppend, None) => {
                bail!("line {line}: stderr redirection needs a path")
            }
            (_, Some(path)) => Some(self.text(path, line)?),
            (_, None) => None,
        };
        Ok(match (target, path) {
            (RedirectTarget::StderrFile, Some(path)) => format!("2>{path}"),
            (RedirectTarget::StderrAppend, Some(path)) => format!("2>>{path}"),
            (RedirectTarget::StderrMerged, _) => "2>&1".to_owned(),
            (RedirectTarget::StdoutToStderr, _) => "1>&2".to_owned(),
            _ => bail!("line {line}: this redirection cannot compile to sh"),
        })
    }

    fn loop_statement(
        &mut self,
        start: usize,
        kind: &LoopKind,
        line: usize,
        depth: usize,
    ) -> Result<()> {
        let body_end = start + self.loop_end(start);
        match kind {
            LoopKind::Repeat { count } => {
                let Value::Integer(count) = count else {
                    bail!("line {line}: repeat counts must be literal integers to compile to sh");
                };
                if *count < 0 {
                    bail!("line {line}: repeat counts cannot be negative");
                }
                let counter = self.fresh_name("repeat");
                self.push(depth, &format!("{counter}=0"));
                self.push(depth, &format!("while [ \"${counter}\" -lt {count} ]; do"));
                self.push(depth + 1, &format!("{counter}=$(({counter} + 1))"));
                self.body(start + 1, body_end - 1, depth + 1)?;
                self.push(depth, "done");
            }
            LoopKind::ForEach { binding, values } => {
                if !is_sh_name(binding) {
                    bail!("line {line}: loop variable {binding:?} is not a valid sh name");
                }
                let Value::List(items) = values else {
                    bail!("line {line}: for each lists must be literal to compile to sh");
                };
                let mut words = Vec::new();
                for item in items {
                    let Value::String(text) = item else {
                        bail!(
                            "line {line}: for each lists must hold literal text to compile to sh"
                        );
                    };
                    words.push(quote(text)?);
                }
                if words.is_empty() {
                    return Ok(());
                }
                let shell_name = self.fresh_name("loop");
                self.push(
                    depth,
                    &format!("for {shell_name} in {}; do", words.join(" ")),
                );
                // Reading the variable keeps shellcheck from calling it unused when the
                // body does not mention it.
                self.push(depth + 1, &format!(": \"${shell_name}\""));
                self.loops.push((binding.clone(), shell_name));
                let result = self.body(start + 1, body_end - 1, depth + 1);
                self.loops.pop();
                result?;
                self.push(depth, "done");
            }
            LoopKind::While { .. } | LoopKind::WhileCommand { .. } => {
                bail!("line {line}: while loops cannot compile to sh yet; use repeat or for each");
            }
        }
        Ok(())
    }

    /// The offset from a loop header to just past its matching EndLoop.
    fn loop_end(&self, start: usize) -> usize {
        match &self.steps[start].kind {
            StepKind::Loop { end, .. } => *end,
            _ => 1,
        }
    }

    /// `if run CMD succeeds|fails`. The parser sets `otherwise` to `end` when there is
    /// no `Otherwise`, so the else branch exists only when `otherwise < end`.
    fn if_statement(&mut self, start: usize, block_end: usize, depth: usize) -> Result<usize> {
        let steps = self.steps;
        let StepKind::IfCommand {
            call,
            expect_success,
            otherwise,
            end,
        } = &steps[start].kind
        else {
            bail!("internal error: expected a command condition");
        };
        let (otherwise, end, expect_success) = (*otherwise, *end, *expect_success);
        let line = steps[start].line;
        let finish = start + end;
        if finish > block_end {
            bail!("line {line}: a condition extends past its block");
        }
        let argv = self.argv(call, line)?;
        let has_else = otherwise < end;
        let then_end = if has_else {
            start + otherwise - 1
        } else {
            finish - 1
        };
        let negate = if expect_success { "" } else { "! " };
        let command = format!("{} >/dev/null 2>&1 </dev/null", argv.words.join(" "));
        self.push(depth, &format!("if {negate}{command}; then"));
        self.body(start + 1, then_end, depth + 1)?;
        if has_else {
            self.push(depth, "else");
            self.body(start + otherwise, finish - 1, depth + 1)?;
        }
        self.push(depth, "fi");
        Ok(finish)
    }
}

/// Only a native command applet whose exit statuses map the default way compiles:
/// status 0 is success and 1-255 are failures. A contract that remaps any status, or
/// an in-process, worker, or program-module applet, has no sh equivalent here.
fn ensure_native_command(manifest: &Manifest, line: usize) -> Result<()> {
    if manifest.builtin.is_some() {
        bail!(
            "line {line}: built-in command {} cannot compile to sh",
            manifest.name
        );
    }
    if manifest.execution_backend() != AppletBackend::Command {
        bail!(
            "line {line}: applet {} is not a native command applet, so it cannot compile to sh",
            manifest.name
        );
    }
    let remapped = (0..=255).any(|status| {
        let outcome = manifest.outcome_for(status);
        let expected = if status == 0 {
            OutcomeKind::Success
        } else {
            OutcomeKind::Failure
        };
        outcome.kind != expected
    });
    if remapped {
        bail!(
            "line {line}: applet {} maps exit statuses by its contract, so it cannot compile to sh",
            manifest.name
        );
    }
    Ok(())
}

fn statement_label(kind: &StepKind) -> &'static str {
    match kind {
        StepKind::Save { .. } => "save to a file",
        StepKind::Append { .. } => "append to a file",
        StepKind::Read { .. } => "read from a file or standard input",
        StepKind::Loop { .. } => "this loop",
        StepKind::If { .. } => "a value condition",
        StepKind::Try { .. } | StepKind::Catch { .. } | StepKind::Finally | StepKind::EndTry => {
            "try and catch"
        }
        StepKind::CallProgram { .. } => "a reusable program call",
        StepKind::TaskGroup { .. } => "a parallel group",
        StepKind::SpawnJob { .. }
        | StepKind::InspectJob { .. }
        | StepKind::AwaitJob { .. }
        | StepKind::CancelJob { .. } => "a background job",
        StepKind::OnInterrupt { .. } => "an interrupt handler",
        StepKind::Interactive => "interactive command handoff",
        StepKind::HandOver => "hand over to a program",
        StepKind::LaunchDetached { .. } => "launch detached",
        StepKind::TempScope { .. } | StepKind::EndTempScope { .. } => "a temporary scope",
        _ => "this statement",
    }
}

