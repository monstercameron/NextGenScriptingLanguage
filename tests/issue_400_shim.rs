use std::fs;
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;
#[cfg(unix)]
use std::path::Path;
use std::path::PathBuf;
use std::process::{Command, Output};

const PROGRAM: &str = "run printf with message \"hi\"\n";

fn shim(directory: &std::path::Path, extra: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(directory)
        .arg("shim")
        .arg(directory.join("hook.program"))
        .args(extra)
        .output()
        .unwrap()
}

fn fixture() -> (tempfile::TempDir, PathBuf) {
    let temp = tempfile::tempdir().unwrap();
    let program = temp.path().join("hook.program");
    fs::write(&program, PROGRAM).unwrap();
    (temp, program)
}

#[test]
fn shim_writes_the_default_stub_and_refuses_to_overwrite() {
    let (temp, program) = fixture();
    let out = temp.path().join("out");
    fs::create_dir(&out).unwrap();
    let out_arg = out.to_string_lossy().into_owned();

    let first = Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(temp.path())
        .arg("shim")
        .arg(&program)
        .args(["--out", &out_arg])
        .output()
        .unwrap();
    assert!(first.status.success(), "{first:?}");
    let stub = fs::read_to_string(out.join("hook.sh")).unwrap();
    let expected_line = format!(
        "exec execute run '{}' -- \"$@\"\n",
        std::path::absolute(&program).unwrap().display()
    );
    assert!(stub.starts_with("#!/usr/bin/env bash\n# Generated by `execute shim`."));
    assert!(stub.ends_with(&expected_line), "{stub}");

    let refused = Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(temp.path())
        .arg("shim")
        .arg(&program)
        .args(["--out", &out_arg])
        .output()
        .unwrap();
    assert!(!refused.status.success());
    assert!(String::from_utf8_lossy(&refused.stderr).contains("--force"));
    assert_eq!(fs::read_to_string(out.join("hook.sh")).unwrap(), stub);

    let forced = Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(temp.path())
        .arg("shim")
        .arg(&program)
        .args(["--out", &out_arg, "--force"])
        .output()
        .unwrap();
    assert!(forced.status.success(), "{forced:?}");
}

#[test]
fn shim_refuses_a_name_with_a_path_separator() {
    let (temp, _program) = fixture();
    let refused = shim(temp.path(), &["--name", "sub/hook.sh"]);
    assert!(!refused.status.success());
    assert!(!temp.path().join("sub").exists());
}

#[cfg(unix)]
#[test]
fn shim_refuses_a_newline_path_and_writes_nothing() {
    let temp = tempfile::tempdir().unwrap();
    let program = temp.path().join("bad\nname.program");
    fs::write(&program, PROGRAM).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(temp.path())
        .arg("shim")
        .arg(&program)
        .args(["--name", "stub.sh"])
        .output()
        .unwrap();
    assert!(!output.status.success());
    assert!(!temp.path().join("stub.sh").exists());
}

// Unix-only: runs the generated stub under bash. The stub must give the same status and
// stdout as running the program directly. This machine is Windows, so this test was not run.
#[cfg(unix)]
#[test]
fn generated_stub_matches_a_direct_run() {
    let (temp, program) = fixture();
    let bin_dir = Path::new(env!("CARGO_BIN_EXE_execute")).parent().unwrap();
    let stub = temp.path().join("hook.sh");
    let written = Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(temp.path())
        .arg("shim")
        .arg(&program)
        .output()
        .unwrap();
    assert!(written.status.success(), "{written:?}");
    let mode = fs::metadata(&stub).unwrap().permissions().mode();
    assert_eq!(mode & 0o777, 0o755);

    let path = format!(
        "{}:{}",
        bin_dir.display(),
        std::env::var("PATH").unwrap_or_default()
    );
    let direct = Command::new(env!("CARGO_BIN_EXE_execute"))
        .current_dir(temp.path())
        .arg("run")
        .arg(&program)
        .output()
        .unwrap();
    let via_stub = Command::new("bash")
        .current_dir(temp.path())
        .arg(&stub)
        .env("PATH", path)
        .output()
        .unwrap();
    assert_eq!(via_stub.status.code(), direct.status.code());
    assert_eq!(via_stub.stdout, direct.stdout);
}
