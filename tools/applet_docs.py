#!/usr/bin/env python3
"""Render docs/applets/core.md from the core applet manifests.

Run with: python tools/applet_docs.py          (writes the page)
          python tools/applet_docs.py --check  (exits 1 when the committed page is stale)

Standard library only. Every manifests/core.*.json becomes one entry, sorted by applet
name: description, phrases, backend, capabilities, declared effects, parameters with
types and required flags, outcomes and the declared examples. tools/test_applet_docs.py
regenerates the page in memory and fails when the committed file differs.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST_GLOB = "core.*.json"
PAGE = Path("docs/applets/core.md")
TITLE = "Core applet reference"


def load_manifests(manifest_dir: Path) -> list[dict]:
    """Return the core applet manifests, sorted by applet name."""
    applets = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in manifest_dir.glob(MANIFEST_GLOB)
    ]
    return sorted(applets, key=lambda applet: applet["name"])


def cell(value) -> str:
    """Make one Markdown table cell: one line, pipes escaped."""
    return " ".join(str(value).split()).replace("|", "\\|")


def slug(heading: str) -> str:
    """GitHub-style anchor for a heading made of an applet name."""
    kept = "".join(ch for ch in heading.lower() if ch.isalnum() or ch in " -_")
    return kept.replace(" ", "-")


def type_text(spec: dict) -> str:
    kind = spec.get("type", "any")
    items = spec.get("items")
    if kind == "list" and items is not None:
        item = items if isinstance(items, str) else json.dumps(items, sort_keys=True)
        return f"list of {item}"
    if "enum" in spec:
        choices = ", ".join(f"`{value}`" for value in spec["enum"])
        return f"{kind}, one of {choices}"
    return str(kind)


def render_applet(applet: dict) -> list[str]:
    contract = applet.get("contract", {})
    name = applet["name"]
    lines = [f"### `{name}`", "", cell(applet.get("description", "")), ""]

    phrases = applet.get("phrases", [])
    if phrases:
        lines += ["Phrases: " + ", ".join(f'"{phrase}"' for phrase in phrases), ""]

    capabilities = contract.get("capabilities", [])
    effects = contract.get("effects", [])
    lifecycle = contract.get("lifecycle", {}).get("kind", "unknown")
    lines += [
        f"- Backend: `{contract.get('backend', 'unknown')}`, lifecycle `{lifecycle}`",
        "- Capabilities: " + (", ".join(f"`{c}`" for c in capabilities) or "none declared"),
        "- Effects: " + (", ".join(f"`{e}`" for e in effects) or "none declared"),
        "",
    ]

    parameters = applet.get("parameters", {})
    if parameters:
        lines += [
            "| Parameter | Type | Required | Description |",
            "| --- | --- | --- | --- |",
        ]
        for pname, spec in parameters.items():
            required = "yes" if spec.get("required") is True else "no"
            lines.append(
                f"| `{cell(pname)}` | {cell(type_text(spec))} | {required} "
                f"| {cell(spec.get('description', ''))} |"
            )
        lines.append("")
    else:
        lines += ["This applet takes no parameters.", ""]

    outcomes = contract.get("outcomes", [])
    if outcomes:
        lines += ["| Outcome | Kind | Status |", "| --- | --- | --- |"]
        for outcome in outcomes:
            lines.append(
                f"| {cell(outcome.get('name', ''))} | {cell(outcome.get('kind', ''))} "
                f"| {cell(outcome.get('status', ''))} |"
            )
        lines.append("")

    examples = applet.get("examples", [])
    if not examples:
        lines += ["No example is declared in the manifest.", ""]
    for example in examples:
        lines += ["Example:", "", "```text", example.get("program", ""), "```", ""]
        if "expected_output" in example:
            expected = json.dumps(example["expected_output"], indent=2, ensure_ascii=False)
            lines += ["Expected output:", "", "```json", expected, "```", ""]
    return lines


def render_page(applets: list[dict]) -> str:
    lines = [
        f"# {TITLE}",
        "",
        "<!-- Generated by tools/applet_docs.py from manifests/core.*.json. "
        "Do not edit by hand: change the manifest and run python tools/applet_docs.py. -->",
        "",
        f"This page lists {len(applets)} core applets, sorted by name.",
        "",
        "## Applets",
        "",
    ]
    for applet in applets:
        name = applet["name"]
        lines.append(f"- [`{name}`](#{slug(name)})")
    lines.append("")
    for applet in applets:
        lines += render_applet(applet)
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root")
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed page differs from the manifests",
    )
    args = parser.parse_args(argv)

    applets = load_manifests(args.root / "manifests")
    text = render_page(applets)
    target = args.root / PAGE
    if args.check:
        current = None
        if target.is_file():
            current = target.read_bytes().decode("utf-8").replace("\r\n", "\n")
        if current != text:
            print(f"{PAGE.as_posix()} is stale; run python tools/applet_docs.py", file=sys.stderr)
            return 1
        print(f"{PAGE.as_posix()} is up to date ({len(applets)} applets)")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(text.encode("utf-8"))
    print(f"wrote {PAGE.as_posix()} ({len(applets)} applets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
